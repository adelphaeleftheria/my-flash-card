export function addSample(data: Data): Data {
  const deck = {
    ...makeDeck("German essentials"),
    description:
      "A small beginning. Everyday words for a world of possibilities.",
  };
  const cards = words.map(
    ([
      German,
      English,
      Example,
      Translation,
      Part,
      Gender,
      Plural,
      IPA,
      Tags,
    ]) =>
      makeCard(deck.id, {
        German,
        English,
        "Example Sentence": Example,
        "Example Translation": Translation,
        "Part of Speech": Part,
        Gender,
        Plural,
        IPA,
        Tags: `A1; ${Tags}`,
        Definition: `${English.charAt(0).toUpperCase() + English.slice(1)} — everyday German vocabulary.`,
      }),
  );
  return {
    ...data,
    decks: [...data.decks, deck],
    cards: [...data.cards, ...cards],
    welcomed: true,
  };
}
